import { createI18n, systemLocale } from '../src/i18n.js';
const tr = createI18n(systemLocale(process.env)).t;
import { mkdir, readFile, writeFile, cp, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const modules = ['i18n', 'model', 'native-client', 'view', 'index'];
const sources = await Promise.all(modules.map(m => readFile(new URL(`src/${m}.js`, root), 'utf8')));
const css = await readFile(new URL('src/navigator.css', root), 'utf8');
const body = sources.map(s => s.replace(/^import .*?;\n/gm, '').replace(/^export /gm, '')).join('\n');
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Worktrees</title><style>html,body{margin:0;background:transparent}</style></head><body><script>(()=>{'use strict';\n${body}\nvoid startNavigator(window,${JSON.stringify(css)});})();</script></body></html>`;
const uri = 'ui://worktree-navigator/' + createHash('sha256').update(html).digest('hex').slice(0, 16) + '.html';
const out = new URL('dist/worktree-navigator/', root);
await rm(out, { recursive: true, force: true }); await mkdir(out, { recursive: true });
await cp(new URL('src/', root), new URL('src/', out), { recursive: true });
await writeFile(new URL('package.json', out), JSON.stringify({ name: 'worktree-navigator', version: pkg.version, license: pkg.license, private: true, type: 'module' }, null, 2) + '\n');
await writeFile(new URL('page.html', out), html);
await writeFile(new URL('resource.json', out), JSON.stringify({ uri }, null, 2) + '\n');
await cp(new URL('plugins/worktree-navigator/plugin.json', root), new URL('plugin.json', out));
console.log(tr('built'));
await cp(new URL('LICENSE', root), new URL('LICENSE', out));
